//! Desktop adapters for an explicitly approved remote-control session.
//!
//! Linux uses the selected X11 screen's root window (possibly a multi-monitor
//! canvas); Windows captures its primary monitor. Wayland hosting, secure
//! desktops, cursor-shape transport, and arbitrary Unicode text are not provided.

use anyhow::{Result, ensure};
use serde::{Deserialize, Serialize};

#[cfg(target_os = "linux")]
#[path = "platform/linux.rs"]
mod linux;
#[cfg(target_os = "windows")]
#[path = "platform/windows.rs"]
mod windows;

pub use crate::protocol::MAX_DIMENSION;

#[derive(Debug)]
pub struct CapturedFrame {
    pub width: u32,
    pub height: u32,
    /// Tightly packed RGBA8 rows, top to bottom. Alpha is always 255.
    pub rgba: Vec<u8>,
}

#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum PointerButton {
    Left,
    Middle,
    Right,
}

