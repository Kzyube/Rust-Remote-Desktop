#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum RemoteInput {
    PointerMove {
        x: u32,
        y: u32,
    },
    Button {
        button: PointerButton,
        pressed: bool,
    },
    Key {
        key: RemoteKey,
        pressed: bool,
    },
    /// Wheel notches: positive scrolls up, negative scrolls down; at most 32.
    Scroll {
        vertical: i32,
    },
}

pub(crate) fn rgba_length(width: u32, height: u32) -> Result<usize> {
    crate::protocol::validate_dimensions(width, height)
}

pub(crate) fn validate_pointer(x: u32, y: u32, width: u32, height: u32) -> Result<()> {
    rgba_length(width, height)?;
    ensure!(
        x < width && y < height,
        "Pointer coordinates are outside the captured desktop"
    );
    Ok(())
}

pub(crate) fn validate_scroll(vertical: i32) -> Result<()> {
    ensure!(
        vertical.unsigned_abs() <= 32,
        "A scroll event may contain at most 32 notches"
    );
    Ok(())
}

#[cfg(target_os = "linux")]
use linux::NativeDesktop;
#[cfg(target_os = "windows")]
use windows::NativeDesktop;

#[cfg(any(target_os = "linux", target_os = "windows"))]
pub struct Desktop {
    inner: NativeDesktop,
}

#[cfg(any(target_os = "linux", target_os = "windows"))]
impl Desktop {
    /// Opens the platform connection and validates display metadata. No pixels
    /// are captured and no input is generated by construction.
    pub fn new() -> Result<Self> {
        Ok(Self {
            inner: NativeDesktop::new()?,
        })
    }

    pub fn capture(&mut self) -> Result<CapturedFrame> {
        self.inner.capture()
    }

    pub fn inject(&mut self, event: RemoteInput) -> Result<()> {
        self.inner.inject(event)
    }

    /// Release keys and buttons held by this session. Call on focus loss,
    /// revocation and disconnect; Drop also attempts it as a final fallback.
    pub fn release_all(&mut self) -> Result<()> {
        self.inner.release_all()
    }
}

#[cfg(any(target_os = "linux", target_os = "windows"))]
impl Drop for Desktop {
    fn drop(&mut self) {
        let _ = self.release_all();
    }
}

#[cfg(not(any(target_os = "linux", target_os = "windows")))]
compile_error!("Desktop capture currently supports Windows and Linux X11 only");

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dimensions_and_pointer_use_exclusive_upper_bounds() {
        assert_eq!(rgba_length(3, 2).unwrap(), 24);
        assert!(rgba_length(0, 10).is_err());
        assert!(rgba_length(MAX_DIMENSION + 1, 1).is_err());
        assert!(rgba_length(8192, 8192).is_err());
        assert!(rgba_length(u32::MAX, u32::MAX).is_err());
        assert!(validate_pointer(99, 49, 100, 50).is_ok());
        assert!(validate_pointer(100, 49, 100, 50).is_err());
        assert!(validate_pointer(99, 50, 100, 50).is_err());
    }

    #[test]
    fn scroll_bound_also_handles_minimum_integer() {
        assert!(validate_scroll(-32).is_ok());
        assert!(validate_scroll(32).is_ok());
        assert!(validate_scroll(33).is_err());
        assert!(validate_scroll(i32::MIN).is_err());
    }
}
